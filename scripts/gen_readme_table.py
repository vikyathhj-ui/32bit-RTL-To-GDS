#!/usr/bin/env python3
"""Regenerate the README results table from results/summary.json (BRIEF A5/A6).

Rewrites everything between the markers
    <!-- TABLE:BEGIN -->  and  <!-- TABLE:END -->
in README.md. Nothing in the table is typed by hand.

    python3 scripts/gen_readme_table.py           # rewrite README.md
    python3 scripts/gen_readme_table.py --check   # exit 1 if README.md is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
README = REPO / "README.md"
BEGIN, END = "<!-- TABLE:BEGIN -->", "<!-- TABLE:END -->"
FLOW = {"default": "default", "preserved": "preserved", "preserved_P1": "preserved, PIPE=1"}


def table(s: dict) -> str:
    rows = []
    for v, archs in s["variants"].items():
        for a, r in archs.items():
            if "area" in r:
                rows.append((v, a, r))
    rows.sort(key=lambda x: x[2]["min_period_ns"])
    signed = {(x["arch"], x["variant"]) for x in s.get("signoff", {}).values() if x["status"] == "PASS"}
    so = next(x for x in s.get("signoff", {}).values() if x["status"] == "PASS")
    rec = s["variants"][so["variant"]][so["arch"]]
    p1 = s["variants"].get(so["variant"] + "_P1", {}).get(so["arch"])
    ir = so["ir_drop_by_activity"]["vcd_activity"]["VPWR"]["worst_drop_V"]
    head = (f"**Recommended:** {so['arch']}, {so['variant']} flow, {so['period_ns']} ns → "
            f"**{rec['fmax_slowest_corner_MHz']} MHz** at the slowest corner, "
            f"{rec['area']['stdcell_area_um2']:.1f} µm² of cells, {rec['power_annotated']['energy_per_op_pJ']:.2f} pJ/op; "
            f"DRC/LVS/antenna clean, worst IR drop {ir * 1e3:.2f} mV.")
    if p1:
        head += (f" With PIPE=1 (one more cycle of latency): **{p1['fmax_slowest_corner_MHz']} MHz**, "
                 f"{p1['area']['stdcell_area_um2']:.1f} µm², {p1['power_annotated']['energy_per_op_pJ']:.2f} pJ/op.")
    v = s.get("verification")
    if v:
        head += (f"\n\n**Verified before layout:** {v['adder_configs_passing']} adder configurations × "
                 f"{v['random_vectors_per_config_verilator']:,} random vectors against the golden model, "
                 f"{v['coverage_percent_min']:.0f}% functional coverage, {v['formal_passed']}/{v['formal_tasks']} "
                 f"formal proofs.")
    out = [head, "",
           "| Adder | Flow | Min period (ns) | fmax @ ss 100 °C 1.60 V (MHz) | fmax @ tt 25 °C (MHz) | "
           "Cell area (µm²) | Energy/op (pJ) | Latency (cycles) |",
           "|---|---|---|---|---|---|---|---|"]
    for v, a, r in rows:
        mark = " ✅ signoff" if (a, v) in signed else ""
        pipe = 1 if v.endswith("_P1") else 0
        out.append(f"| **{a}**{mark} | {FLOW[v]} | {r['min_period_ns']} | {r['fmax_slowest_corner_MHz']} | "
                   f"{r['timing']['nom_tt_025C_1v80']['fmax_MHz']} | {r['area']['stdcell_area_um2']:.1f} | "
                   f"{r['power_annotated']['energy_per_op_pJ']:.2f} | {2 + pipe} |")
    out.append("")
    out.append(f"Generated by `scripts/gen_readme_table.py` from `results/summary.json`. "
               f"{len(rows)} closing runs on sky130A / `sky130_fd_sc_hd`, sorted by period. Min period: "
               f"{s['closing_criterion']}, {s['period_resolution_ns']} ns steps. Energy/op = power from a "
               f"gate-level workload VCD × period.")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    s = json.loads((REPO / "results" / "summary.json").read_text())
    text = README.read_text()
    if BEGIN not in text or END not in text:
        print(f"README.md has no {BEGIN} / {END} markers")
        return 1
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: f"{BEGIN}\n{table(s)}\n{END}", text,
                 flags=re.S)
    if a.check:
        if new != text:
            print("README.md table is stale: run python3 scripts/gen_readme_table.py")
            return 1
        print("README.md table is up to date")
        return 0
    README.write_text(new)
    print("README.md table regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
