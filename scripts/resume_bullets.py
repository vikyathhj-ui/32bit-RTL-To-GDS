#!/usr/bin/env python3
"""Write results/resume_bullets.md: 3 resume bullets whose every number comes from summary.json (BRIEF A5).

The sentences are templates; the script fills in the numbers, so no figure is
typed by hand and the bullets can be regenerated after any re-run.

    python3 scripts/resume_bullets.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
S = json.loads((REPO / "results" / "summary.json").read_text())


def main() -> int:
    v = S["verification"]
    pre, dft = S["variants"]["preserved"], S["variants"]["default"]
    so = next(x for x in S["signoff"].values() if x["status"] == "PASS")
    rec = S["variants"][so["variant"]][so["arch"]]
    runs = sum(len(a) for a in S["variants"].values())
    archs = len(pre)
    abc = {(r["arch"], r["variant"]): r for r in S["abc_experiment"]["results"]}
    ks_d, ks_p = abc[("KS", "default")], abc[("KS", "preserved")]
    d_lo = min(r["min_period_ns"] for r in dft.values())
    d_hi = max(r["min_period_ns"] for r in dft.values())
    p1 = S["variants"].get("preserved_P1", {}).get(so["arch"])
    ir = so["ir_drop_by_activity"]["vcd_activity"]["VPWR"]

    b1 = (f"Designed and verified a 32-bit RV32I + Zbb ALU with {archs} switchable adder "
          f"architectures (ripple, CLA, carry-select, Brent–Kung, Kogge–Stone, Sklansky, Han–Carlson, behavioural); "
          f"{v['random_vectors_per_config_verilator']:,} constrained-random vectors per configuration against a "
          f"Spike-checked Python golden model, {v['coverage_percent_min']:.0f}% functional coverage, and "
          f"{v['formal_passed']}/{v['formal_tasks']} SymbiYosys equivalence and protocol proofs.")
    b2 = (f"Ran {runs} RTL-to-GDS closures on SKY130 (LibreLane, {len(rec['timing'])} PVT/RC corners, {S['period_resolution_ns']} ns period search) and "
          f"showed that default ABC synthesis erases the adder architectures (Kogge–Stone logic depth "
          f"{ks_p['logic_depth']} → {ks_d['logic_depth']}; all {archs} designs within {d_lo}–{d_hi} ns); preserving "
          f"the prefix structure reached {rec['fmax_slowest_corner_MHz']} MHz at the slow corner.")
    b3 = (f"Signed off the Han–Carlson configuration (DRC/LVS/antenna clean, VCD-annotated IR drop "
          f"{ir['worst_drop_V'] * 1e3:.2f} mV) with gate-level-simulation power ({rec['power_annotated']['energy_per_op_pJ']:.2f} "
          f"pJ/op); traced the critical path to the shifter and zero-flag logic, not the adder")
    if p1:
        b3 += (f", and pipelining it raised fmax from {rec['fmax_slowest_corner_MHz']} to "
               f"{p1['fmax_slowest_corner_MHz']} MHz at the cost of one cycle of latency.")
    else:
        b3 += "."
    out = REPO / "results" / "resume_bullets.md"
    out.write_text("# Resume bullets\n\nGenerated by `scripts/resume_bullets.py`; every number comes from "
                   "`results/summary.json`.\n\n" + "\n".join(f"- {b}" for b in (b1, b2, b3)) + "\n")
    print(out.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
